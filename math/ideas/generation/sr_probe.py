def order_ideal_faces(masks, n):
    """NC(F): all subsets of [n] contained in some member of F, as frozensets.
    Downward closed simplicial complex on [n]. Includes empty face."""
    faces = set()
    faces.add(frozenset())
    for m in masks:
        elts = [i for i in range(n) if (m >> i) & 1]
        # add all subsets of elts -- but only need to add m's subsets; do via
        # generating subsets of the maximal members for efficiency
        for r in range(len(elts) + 1):
            for c in itertools.combinations(elts, r):
                faces.add(frozenset(c))
    return faces


def maximal_members(masks):
    ms = list(masks)
    maxs = []
    for a in ms:
        if a == 0:
            continue
        if not any(a != b and (a & b) == a for b in ms):  # a subset of b, a!=b
            maxs.append(a)
    return maxs


def order_complex_of_lattice_euler(masks):
    """Reduced Euler characteristic of the order complex of the OPEN interval
    (0hat,1hat) of Lhat = L (which already has 0hat=emptyset) with 1hat=top
    adjoined if needed.  Equivalently Mobius(0hat,1hat).  Control invariant."""
    # L = masks (assume emptyset in masks as 0hat). top = union of all.
    L = sorted(set(masks))
    if 0 not in L:
        L = [0] + L
    top = 0
    for m in L:
        top |= m
    if top not in L:
        L = L + [top]
    # proper part P = L \ {0, top}
    P = [m for m in L if m != 0 and m != top]
    # order complex: chains in P. reduced Euler char = sum (-1)^(|chain|-1)
    # = Mobius(0,top) by Philip Hall.  Compute Mobius directly.
    Lset = sorted(set(L))
    @lru_cache(maxsize=None)
    def mob(a, b):
        if a == b:
            return 1
        # sum over a<=z<b of mob(a,z), negated
        s = 0
        for z in Lset:
            if z == b:
                continue
            if (a & z) == a and (z & b) == z and z != b:  # a<=z<b
                if z == a or (a & z) == a:
                    if (z & b) == z and z != b and (a & z) == a:
                        s += mob(a, z)
        return -s
    return mob(0, top)


# ----------------------------------------------------------------------------
# the homological "cone apex" notions
# ----------------------------------------------------------------------------

def apex_vertices(masks, n):
    """Vertices x of NC(F) that are CONE APEXES: x lies in every maximal member.
    If NC(F) has a cone apex x then NC(F) is contractible with apex x, and x is
    an abundant element candidate."""
    maxs = maximal_members(masks)
    if not maxs:
        return []
    out = []
    for x in range(n):
        bit = 1 << x
        if all(m & bit for m in maxs):
            out.append(x)
    return out


def main(nmax):
    rows = []
    n_fail_apex = 0
    n_fam = 0
    # candidate-inequality trackers
    worst_apex_abund = 1.0
    worst_reg_minus = None
    cone_dead_check = []  # (euler) distribution
    nonflat_cube = {}

    for n in range(0, nmax + 1):
        for F in all_uc_families(n):
            if not F:
                continue
            masks = set(F)
            masks.add(0)  # adjoin emptyset (bottom). F.2 convention.
            nn = ground_set(frozenset(masks))
            if nn == 0:
                continue
            freqs = frequencies(list(masks), nn)
            sizeF = len(masks)
            abund = max(freqs) / sizeF
            n_fam += 1

            # (B) order ideal complex NC(F) on [nn]
            faces = order_ideal_faces(masks, nn)
            betti = reduced_homology_ranks(faces)
            total_betti = sum(abs(b) for b in betti)
            reduced_euler = sum(((-1) ** (k - 1)) * b
                                for k, b in zip(range(-1, len(betti) - 1), betti))

            # (D) cone apex vertices of NC(F)
            apex = apex_vertices(masks, nn)
            apex_freqs = [freqs[x] for x in apex]
            apex_abund = (max(apex_freqs) / sizeF) if apex else None

            # the candidate claim: if NC(F) has a cone apex, abundance>=1/2?
            if apex:
                # apex vertex is in every maximal member, so freq(apex) is large
                a_ab = max(apex_freqs) / sizeF
                worst_apex_abund = min(worst_apex_abund, a_ab)

            # (A) control: order complex euler (mobius)
            try:
                eul = order_complex_of_lattice_euler(masks)
            except Exception:
                eul = None

            rows.append({
                "n": nn, "sizeF": sizeF, "abund": abund,
                "betti": betti, "total_betti": total_betti,
                "reduced_euler": reduced_euler,
                "n_apex": len(apex), "apex_abund": apex_abund,
                "mobius_orderL": eul,
                "freqs": sorted(freqs, reverse=True),
            })

    return rows, {
        "n_fam": n_fam,
        "worst_apex_abund": worst_apex_abund,
    }


