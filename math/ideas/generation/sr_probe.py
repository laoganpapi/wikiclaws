"""
sr_probe.py — Stanley-Reisner / homological probe for Frankl's union-closed
conjecture.  Lives under math/ideas/generation/ (idea-generation only).

GOAL.  Test whether a *labelling-sensitive* homological invariant of a complex
built from a union-closed family F correlates with / lower-bounds the abundance
max_x freq(x)/|F|.  The cone obstruction (lattice_attack.md sec.4) kills every
invariant of the ABSTRACT lattice L=(F,union).  So we deliberately build complexes
on the GROUND SET [n] (the labelling F.2 data), not on the poset L.

We compute, per UC family F (with emptyset adjoined) over n<=5:

  (A) order complex of L : reduced Euler characteristic = Mobius(0,1) of Lhat.
      [control: this is a poset/cone invariant, expected DEAD under coning]

  (B) the "non-cover complex" NC(F): simplicial complex on vertex set [n] whose
      faces are the subsets S<=[n] that are CONTAINED in some member of F
      (i.e. S is a face iff S subset of A for some A in F).  This is the order
      ideal generated by F in 2^[n] -- a genuine simplicial complex on [n].
      Its Stanley-Reisner ring k[NC] is the object of Hochster/Reisner/EagonReiner.
      Under the cone G -> cone(G) (adjoin fresh z to every nonempty set), NC(cone)
      is the TOPOLOGICAL CONE z * NC'(G) and z is exactly the abundant vertex.

  (C) Hochster data: for the Alexander dual NC(F)^vee, projective dimension of
      k[NC] = reg(I_{NC^vee}) (Eagon-Reiner).  We instead directly compute the
      reduced homology Betti numbers of induced subcomplexes (Hochster) and the
      total Betti number, plus per-vertex "link contractibility" (cone test).

  (D) cone-vertex test: a vertex x of a complex Delta is a CONE APEX iff
      every facet contains x iff link(x)=del(x) iff x in every maximal face.
      For NC(F), x is an apex iff x in every maximal member of F.  We compare
      "x is an apex of NC(F)" and softer homological notions to abundance.

Output: a JSONL row per family + a summary with candidate inequalities.

Run:  python3 sr_probe.py 5
"""
