# ----------------------------------------------------------------------------
# basic homology over Q (rational) by rank of boundary maps (Smith-free: use
# numeric rank via fraction-free Gaussian elimination on small integer matrices)
# ----------------------------------------------------------------------------

def _rank_mod_p(rows, p=1000003):
    """Rank of an integer matrix mod a large prime (fast, faithful for small,
    sparse, small-entry matrices we generate). Returns integer rank."""
    M = [list(r) for r in rows]
    if not M:
        return 0
    ncol = len(M[0]) if M else 0
    rank = 0
    col = 0
    nrow = len(M)
    r = 0
    while r < nrow and col < ncol:
        piv = None
        for i in range(r, nrow):
            if M[i][col] % p != 0:
                piv = i
                break
        if piv is None:
            col += 1
            continue
        M[r], M[piv] = M[piv], M[r]
        inv = pow(M[r][col] % p, p - 2, p)
        M[r] = [(v * inv) % p for v in M[r]]
        for i in range(nrow):
            if i != r and M[i][col] % p != 0:
                f = M[i][col] % p
                M[i] = [(a - f * b) % p for a, b in zip(M[i], M[r])]
        r += 1
        rank += 1
        col += 1
    return rank


def reduced_homology_ranks(faces):
    """Given a simplicial complex as a set of faces (each a frozenset of vertex
    ints), INCLUDING the empty face for reduced homology, return the list of
    reduced Betti numbers [b_{-1}, b_0, b_1, ...] over F_p.

    Uses augmented chain complex (reduced homology).  Faces must be downward
    closed (a simplicial complex)."""
    # group faces by dimension (dim = |face|-1). include empty face (dim -1).
    by_dim = {}
    for f in faces:
        d = len(f) - 1
        by_dim.setdefault(d, []).append(tuple(sorted(f)))
    if not by_dim:
        return []
    maxd = max(by_dim)
    # ensure empty face present for reduced homology
    by_dim.setdefault(-1, [tuple()])
    for d in by_dim:
        by_dim[d].sort()
    index = {d: {f: i for i, f in enumerate(by_dim[d])} for d in by_dim}
    # boundary map d_k : C_k -> C_{k-1}
    ranks = {}
    for k in range(0, maxd + 1):
        if k not in by_dim or (k - 1) not in by_dim:
            ranks[k] = 0
            continue
        rows = []  # one row per (k-1)-face, columns per k-face -> but rank is same transposed
        kfaces = by_dim[k]
        km1 = index[k - 1]
        mat = []
        for f in kfaces:
            col = [0] * len(km1)
            for j in range(len(f)):
                face = f[:j] + f[j + 1:]
                sign = -1 if (j % 2) else 1
                col[km1[face]] += sign
            mat.append(col)  # row = this k-face's boundary in C_{k-1}
        ranks[k] = _rank_mod_p(mat)
    # reduced betti: b_k = dim C_k - rank d_k - rank d_{k+1}
    betti = []
    for k in range(-1, maxd + 1):
        ck = len(by_dim.get(k, []))
        rk = ranks.get(k, 0)          # rank of d_k : C_k -> C_{k-1}
        rk1 = ranks.get(k + 1, 0)     # rank of d_{k+1}: C_{k+1} -> C_k
        betti.append(ck - rk - rk1)
    return betti


